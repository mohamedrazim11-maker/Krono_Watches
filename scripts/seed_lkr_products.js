function resolveLocalImage(id) {
  if (SPECIFIC_IMAGES[id]) return SPECIFIC_IMAGES[id];
  let h = 0;
  for (let i = 0; i < id.length; i++) h += id.charCodeAt(i);
  return LOCAL_IMAGES[h % LOCAL_IMAGES.length];
}

